impl RenameStrings {
    pub fn count(template: &str, n: usize) -> String {
        template.replace("{n}", &n.to_string())
    }
    pub fn progress(template: &str, done: usize, total: usize) -> String {
        template
            .replace("{done}", &done.to_string())
            .replace("{total}", &total.to_string())
    }
    pub fn state(&self, state: State) -> String {
        match state {
            State::Pending => self.state_pending.into(),
            State::Ready => self.state_ready.into(),
            State::Unchanged => self.state_unchanged.into(),
            State::NoDate => self.state_no_date.into(),
            State::OnlineOnly => self.state_online_only.into(),
            State::Unreadable => self.state_unreadable.into(),
            State::CodecMissing(codec) => self.state_codec_missing.replace("{codec}", codec),
            State::Conflict => self.state_conflict.into(),
        }
    }
    pub fn source(&self, source: TimeSource) -> &'static str {
        match source {
            TimeSource::ExifOriginal => self.source_exif_original,
            TimeSource::ExifDigitized => self.source_exif_digitized,
            TimeSource::QuickTimeLocal => self.source_quicktime_local,
            TimeSource::QuickTimeUtc => self.source_quicktime_utc,
            TimeSource::Encoded => self.source_encoded,
            TimeSource::Modified => self.source_modified,
        }
    }
    /// The display label of a metadata section; EXIF, GPS, XMP and file-format blocks keep
    /// their technical names.
    pub fn metadata_section<'a>(&'a self, section: &'a str) -> &'a str {
        match section {
            exif::IMAGE_SECTION => self.section_image,
            exif::THUMBNAIL_SECTION => self.section_thumbnail,
            exif::PROPERTIES_SECTION => self.section_properties,
            other => other,
        }
    }
    pub fn template_error(&self, error: &TemplateError) -> String {
        match error {
            TemplateError::Empty => self.error_empty.into(),
            TemplateError::TooLong => self.error_too_long.into(),
            TemplateError::Unbalanced => self.error_unbalanced.into(),
            TemplateError::Unknown(token) => self
                .error_unknown
                .replace("{token}", &format!("{{{token}}}")),
            TemplateError::Control => self.error_control.into(),
        }
    }
}

