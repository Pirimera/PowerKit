#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn placeholders_survive_in_every_catalog() {
        for strings in [&TR, &EN, &AR] {
            for template in [strings.companions, strings.applied, strings.tray_ready] {
                assert!(template.contains("{n}"));
            }
            for template in [strings.scanning, strings.applying, strings.undoing] {
                assert!(template.contains("{done}") && template.contains("{total}"));
            }
            assert!(strings.state_codec_missing.contains("{codec}"));
            assert!(strings.error_unknown.contains("{token}"));
            assert!(strings.journal_failed.contains("{error}"));
        }
        assert_eq!(
            RenameStrings::count(TR.applied, 3),
            "3 dosya yeniden adlandırıldı."
        );
        assert_eq!(
            EN.state(State::CodecMissing("HEIF Image Extensions")),
            "Needs HEIF Image Extensions"
        );
        assert_eq!(
            TR.template_error(&TemplateError::Unknown("foo".into())),
            "Bilinmeyen belirteç: {foo}"
        );
    }
}
