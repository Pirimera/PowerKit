impl MouseStrings {
    pub fn action(&self, action: &Action) -> &'static str {
        match action {
            Action::None => self.action_none,
            Action::LeftClick => self.action_left_click,
            Action::RightClick => self.action_right_click,
            Action::MiddleClick => self.action_middle_click,
            Action::MouseBack => self.action_mouse_back,
            Action::MouseForward => self.action_mouse_forward,
            Action::BrowserBack => self.action_browser_back,
            Action::BrowserForward => self.action_browser_forward,
            Action::TaskView => self.action_task_view,
            Action::PreviousDesktop => self.action_previous_desktop,
            Action::NextDesktop => self.action_next_desktop,
            Action::ShowDesktop => self.action_show_desktop,
            Action::Copy => self.action_copy,
            Action::Paste => self.action_paste,
            Action::Cut => self.action_cut,
            Action::Undo => self.action_undo,
            Action::Redo => self.action_redo,
            Action::SelectAll => self.action_select_all,
            Action::Find => self.action_find,
            Action::Save => self.action_save,
            Action::NewTab => self.action_new_tab,
            Action::CloseTab => self.action_close_tab,
            Action::ReopenTab => self.action_reopen_tab,
            Action::NextTab => self.action_next_tab,
            Action::PrevTab => self.action_prev_tab,
            Action::ReloadPage => self.action_reload,
            Action::PlayPause => self.action_play_pause,
            Action::NextTrack => self.action_next_track,
            Action::PrevTrack => self.action_prev_track,
            Action::VolumeUp => self.action_volume_up,
            Action::VolumeDown => self.action_volume_down,
            Action::MuteVolume => self.action_mute,
            Action::CaptureRegion => self.action_capture_region,
            Action::LockScreen => self.action_lock,
            Action::PinLastWindow => self.action_pin_last,
            Action::StartScreenRuler => self.action_start_ruler,
            Action::OpenPowerKit => self.action_open_powerkit,
            Action::Custom(_) => self.pass_through,
        }
    }

    pub fn trigger(&self, trigger: crate::power_mouse::Trigger) -> &'static str {
        match trigger {
            crate::power_mouse::Trigger::Middle => self.trigger_middle,
            crate::power_mouse::Trigger::Back => self.trigger_back,
            crate::power_mouse::Trigger::Forward => self.trigger_forward,
            crate::power_mouse::Trigger::TiltLeft => self.trigger_tilt_left,
            crate::power_mouse::Trigger::TiltRight => self.trigger_tilt_right,
            crate::power_mouse::Trigger::F13 => "F13",
            crate::power_mouse::Trigger::F14 => "F14",
            crate::power_mouse::Trigger::F15 => "F15",
            crate::power_mouse::Trigger::F16 => "F16",
            crate::power_mouse::Trigger::F17 => "F17",
            crate::power_mouse::Trigger::F18 => "F18",
            crate::power_mouse::Trigger::F19 => "F19",
            crate::power_mouse::Trigger::F20 => "F20",
            crate::power_mouse::Trigger::F21 => "F21",
            crate::power_mouse::Trigger::F22 => "F22",
            crate::power_mouse::Trigger::F23 => "F23",
            crate::power_mouse::Trigger::F24 => "F24",
        }
    }

    /// Catalog actions only (no pass-through); used for binding slots.
    pub fn action_labels(&self) -> Vec<&'static str> {
        Action::CATALOG
            .iter()
            .map(|action| self.action(action))
            .collect()
    }
}

